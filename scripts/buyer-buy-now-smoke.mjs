import {execFileSync} from 'node:child_process';
const base=process.env.BUYER_TEST_URL, db=process.env.BUYER_TEST_DATABASE;
if(!base || !/^CloneEbayBuyer_Test_[A-Za-z0-9_]+$/.test(db??'') || !process.env.BUYER_TEST_PASSWORD)throw Error('Dedicated test URL/database/password required');
const sql=q=>execFileSync('sqlcmd',['-S',process.env.BUYER_TEST_SQL_SERVER??'.\\SQLEXPRESS','-E','-C','-I','-b','-d',db,'-h','-1','-W','-Q','SET NOCOUNT ON; '+q],{encoding:'utf8'}).trim();
let checks=0;const check=(v,m)=>{if(!v)throw Error(m);checks++};
let token;
async function api(path,method='GET',body,status=200){const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});const j=await r.json();check(r.status===status,`${path}: ${r.status} ${j.message}`);return j.data;}
token=(await api('/api/auth/login','POST',{email:'seed.buyer01@example.test',password:process.env.BUYER_TEST_PASSWORD})).accessToken;
sql('UPDATE Listing SET quantity=20 WHERE id IN (1,2)');
const address=(await api('/api/addresses'))[0].id;
await api('/api/cart/items','POST',{listingId:2,quantity:1});
const cart=JSON.stringify(await api('/api/cart'));
const before=Number(sql('SELECT COUNT(*) FROM CheckoutGroup'));
const request={addressId:address,method:'PAYPAL',listingId:1,quantity:2};
const quote=await api('/api/checkout/preview','POST',request);
check(quote.items.length===1 && quote.items[0].listingId===1 && quote.items[0].quantity===2,'only selected listing');
check(Number(sql('SELECT COUNT(*) FROM CheckoutGroup'))===before,'preview creates no orders');
check(Number(sql('SELECT quantity FROM Listing WHERE id=1'))===20,'preview reserves no stock');
const order=await api('/api/checkout','POST',request);
check(order.totalAmount===quote.totalAmount && order.status==='PENDING','paypal pending at quoted total');
check(JSON.stringify(await api('/api/cart'))===cart,'buy now preserves existing cart');
check(Number(sql('SELECT quantity FROM Listing WHERE id=1'))===18,'selected quantity deducted');
check(Number(sql('SELECT COUNT(*) FROM CartItem WHERE listingId=1 AND cartId IN (SELECT id FROM Cart WHERE userId=1)'))===0,'buy now does not add to cart');
await api(`/api/checkout/${order.checkoutGroupId}/cancel`,'POST',{});
check(Number(sql('SELECT quantity FROM Listing WHERE id=1'))===20,'cancel restores selected stock');
const cod=await api('/api/checkout','POST',{...request,method:'COD',quantity:1});check(cod.status==='CONFIRMED','COD confirms without online payment');
await api('/api/checkout/preview','POST',{...request,quantity:0},400);
await api('/api/checkout/preview','POST',{...request,listingId:999999},404);
await api('/api/checkout/preview','POST',{...request,listingId:41},409);
await api('/api/checkout/preview','POST',{...request,quantity:1000},409);
console.log(`PASS: ${checks} Buy It Now assertions.`);
